def clean_body(txt):
    """从合并的 body 文本里拆出标题、副标题、要点行"""
    lines = [x.strip() for x in txt.split("\n")]
    lines = [x for x in lines if x and not re.fullmatch(r"\d{1,2}", x)]
    title = lines[0] if lines else ""
    sub = lines[1] if len(lines) > 1 else ""
    return title, sub, lines[2:]


def page_block(doc, no):
    v = data[str(no)]
    title, sub, points = clean_body(v["items"][0]["t"]) if v["items"] else ("", "", [])
    if not title:
        title = v.get("title", "")
    mins = META.get(no, 3)
    cut = CUT.get(no, "")

    # 页头
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(10)
    p.paragraph_format.space_after = Pt(2)
    set_run(p.add_run("P%02d　" % no), size=21, bold=True, color=O, name="Arial")
    set_run(p.add_run(title), size=21, bold=True, color=M)
    set_run(p.add_run("　　%d 分钟" % mins), size=16, color=SUB)
    if cut:
        set_run(p.add_run("　　【%s】" % cut), size=15, bold=True,
                color=R if "必留" in cut else G)
    if sub:
        P(doc, sub, size=16, color=SUB, space_before=0, space_after=3, line=1.4)

    # 要点
    for i, ln in enumerate(points):
        if CHAPTER_PAGES and no in CHAPTER_PAGES and no != 1:
            break
        BUL(doc, ln, size=17, indent=0.5, mark="▸", mark_color=M)

    # 提示词
    for it in v["items"]:
        if it["k"] == "plabel":
            P(doc, it["t"], size=15, bold=True, color=O, space_before=4, space_after=1)
        elif it["k"] == "prompt":
            BOX(doc, "", [it["t"].replace("\n", "\n")], fill_hex="F4F8FA", bar=M)
    # 提醒
    for it in v["items"]:
        if it["k"] == "note":
            P(doc, "提醒　" + it["t"], size=16, color=O, space_before=3, space_after=2, line=1.45)


