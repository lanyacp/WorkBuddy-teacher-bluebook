def extract_title(path):
    txt = open(path, encoding="utf-8").read()
    m = re.search(r"fontSize:34, fontWeight:'bold', color:'#[0-9A-Fa-f]{6}' }}>(.*?)</Text>", txt)
    if m:
        return m.group(1).strip()
    m = re.search(r"fontSize:56, fontWeight:'bold', color:'#FFFFFF'[^>]*>(.*?)</Text>", txt)
    if m:
        return m.group(1).strip()
    m = re.search(r"fontSize:46, fontWeight:'bold'[^>]*>(.*?)</Text>", txt, re.S)
    if m:
        return m.group(1).replace("<br />", " / ").strip()
    return os.path.basename(path)


