    total = 0
    img_total = 0

    for rel, title in FILES:
        path = os.path.join(BASE, rel)
        if not os.path.exists(path):
            print("  [跳过] 找不到文件：%s" % rel)
            continue
        text = open(path, encoding="utf-8").read()
        if PUBLIC_MODE:
            text = strip_personal(text)
        n_img = text.count("\n![")
        total += len(text)
        img_total += n_img
        parts.append("\n\n---\n\n# %s\n\n%s" % (title, text))
        print("  [合并] %-38s %6.1f KB  图 %2d 张" % (rel, len(text) / 1024, n_img))

