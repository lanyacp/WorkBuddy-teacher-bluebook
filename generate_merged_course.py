from docx.oxml import parse_xml

C_MAIN = RGBColor(0x1a, 0x5f, 0x7a)
C_GREEN = RGBColor(0x2e, 0x7d, 0x32)
C_ORANGE = RGBColor(0xf5, 0x7c, 0x00)
C_RED = RGBColor(0xc0, 0x00, 0x00)
C_GRAY = RGBColor(0x33, 0x33, 0x33)

def set_run_font(run, font_name='微软雅黑', size=10.5, bold=False, color=None):
    run.font.name = font_name
    run._element.rPr.rFonts.set(qn('w:eastAsia'), font_name)
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = color

def H(doc, text, level=1):
    h = doc.add_heading(level=level)
    run = h.add_run(text)
    if level == 1:
        set_run_font(run, size=16, bold=True, color=C_MAIN)
    elif level == 2:
        set_run_font(run, size=14, bold=True, color=C_GREEN)
    elif level == 3:
        set_run_font(run, size=12, bold=True, color=C_ORANGE)
    else:
        set_run_font(run, size=11, bold=True)
    h.alignment = WD_ALIGN_PARAGRAPH.LEFT
    return h

def P(doc, text, bold=False, indent=True, size=10.5, color=None):
    p = doc.add_paragraph()
    if indent:
        p.paragraph_format.first_line_indent = Cm(0.74)
    p.paragraph_format.line_spacing = 1.5
    run = p.add_run(text)
    set_run_font(run, size=size, bold=bold, color=color)
    return p

def BUL(doc, text, level=0, size=10.5, color=None):
    p = doc.add_paragraph(style='List Bullet')
    p.paragraph_format.left_indent = Cm(0.74 + level * 0.5)
    p.paragraph_format.line_spacing = 1.5
    run = p.add_run(text)
    set_run_font(run, size=size, color=color)
    return p

def NUM(doc, text, level=0, size=10.5):
    p = doc.add_paragraph(style='List Number')
    p.paragraph_format.left_indent = Cm(0.74 + level * 0.5)
    p.paragraph_format.line_spacing = 1.5
    run = p.add_run(text)
    set_run_font(run, size=size)
    return p

def fill(cell, hex_color):
    xml = '<w:shd xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main" w:fill="' + hex_color + '"/>'
    cell._tc.get_or_add_tcPr().append(parse_xml(xml))

def quote_box(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(0.74)
    p.paragraph_format.line_spacing = 1.4
    run = p.add_run('“' + text + '”')
    set_run_font(run, size=9.5, color=C_GRAY)
    run.italic = True
    return p

def prompt_box(doc, title, content):
    P(doc, '【' + title + '】', bold=True, indent=False, color=C_MAIN)
    p = doc.add_paragraph()
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.left_indent = Cm(0.74)
    run = p.add_run(content)
    set_run_font(run, size=9, color=C_GRAY)
    return p

def make_table(doc, headers, rows, widths, header_color='1A5F7A', font_size=8.5):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, htext in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = htext
        for para in c.paragraphs:
            para.alignment = WD_ALIGN_PARAGRAPH.CENTER
            for r in para.runs:
                set_run_font(r, size=font_size, bold=True, color=RGBColor(0xff, 0xff, 0xff))
        fill(c, header_color)
    for ri, row in enumerate(rows, start=1):
        for ci, text in enumerate(row):
            c = t.rows[ri].cells[ci]
            c.text = text
            for para in c.paragraphs:
                para.alignment = WD_ALIGN_PARAGRAPH.LEFT
                para.paragraph_format.line_spacing = 1.25
                for r in para.runs:
                    set_run_font(r, size=font_size)
    for row in t.rows:
        for ci, w in enumerate(widths):
            row.cells[ci].width = Inches(w)
    return t

def MODULE(doc, title, goal, methods, tools, pain_intro, gen_intro, steps, prompts, output):
    """统一的培训模块排版块"""
    H(doc, title, 3)
    P(doc, '【模块目标】', bold=True, indent=False)
    P(doc, goal, indent=True)
    P(doc, '【对应融合方法】', bold=True, indent=False)
    P(doc, methods, indent=True, color=C_GREEN)
    P(doc, '【使用工具】', bold=True, indent=False)
    P(doc, tools, indent=True, color=C_MAIN)
    if pain_intro:
        P(doc, '【真实痛点引入】', bold=True, indent=False, color=C_RED)
        P(doc, pain_intro, indent=True)
    if gen_intro:
        P(doc, '【生成性质活动】', bold=True, indent=False, color=C_ORANGE)
        P(doc, gen_intro, indent=True)
    P(doc, '【教师操作步骤】', bold=True, indent=False)
    for s in steps:
        NUM(doc, s)
    if prompts:
        for t_, c_ in prompts:
            prompt_box(doc, t_, c_)
    P(doc, '【学员当场实操产出】', bold=True, indent=False, color=C_GREEN)
    P(doc, output, indent=True)

