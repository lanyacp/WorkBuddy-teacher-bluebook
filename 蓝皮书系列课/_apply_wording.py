# ---- 校验后统一写入 ----
data = {}
for fn, old, new, cnt in E:
    if fn not in data:
        data[fn] = (BASE / fn).read_text(encoding="utf-8")
    c = data[fn].count(old)
    assert c >= cnt, "MISS [%s] count=%d :: %r" % (fn, c, old[:60])

for fn, old, new, cnt in E:
    data[fn] = data[fn].replace(old, new, cnt)

for fn, text in data.items():
    (BASE / fn).write_text(text, encoding="utf-8")

print("applied", len(E), "edits across", len(data), "files")
